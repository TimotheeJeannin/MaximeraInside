// Single-stroke glyphs for engraving, in a 1-unit-high box (y up).
const GLYPHS = {
    0: [0.6, [[[0, 0], [0.6, 0], [0.6, 1], [0, 1], [0, 0]]]],
    1: [0.6, [[[0.15, 0.8], [0.3, 1], [0.3, 0]], [[0.1, 0], [0.5, 0]]]],
    2: [0.6, [[[0, 1], [0.6, 1], [0.6, 0.5], [0, 0.5], [0, 0], [0.6, 0]]]],
    3: [0.6, [[[0, 1], [0.6, 1], [0.6, 0], [0, 0]], [[0.1, 0.5], [0.6, 0.5]]]],
    4: [0.6, [[[0, 1], [0, 0.5], [0.6, 0.5]], [[0.6, 1], [0.6, 0]]]],
    5: [0.6, [[[0.6, 1], [0, 1], [0, 0.5], [0.6, 0.5], [0.6, 0], [0, 0]]]],
    6: [0.6, [[[0.6, 1], [0, 1], [0, 0], [0.6, 0], [0.6, 0.5], [0, 0.5]]]],
    7: [0.6, [[[0, 1], [0.6, 1], [0.2, 0]]]],
    8: [0.6, [[[0, 0], [0.6, 0], [0.6, 1], [0, 1], [0, 0]], [[0, 0.5], [0.6, 0.5]]]],
    9: [0.6, [[[0, 0], [0.6, 0], [0.6, 1], [0, 1], [0, 0.5], [0.6, 0.5]]]],
    '.': [0.1, [[[0, 0], [0.1, 0], [0.1, 0.1], [0, 0.1], [0, 0]]]],
    '-': [0.4, [[[0, 0.5], [0.4, 0.5]]]],
    '+': [0.4, [[[0, 0.5], [0.4, 0.5]], [[0.2, 0.3], [0.2, 0.7]]]],
    K: [0.6, [[[0, 0], [0, 1]], [[0.6, 1], [0, 0.4]], [[0.2, 0.6], [0.6, 0]]]],
    T: [0.6, [[[0, 1], [0.6, 1]], [[0.3, 1], [0.3, 0]]]],
    ' ': [0.3, []],
};
const GAP = 0.25;

// Open polylines spelling `text`, centred on x with its baseline at y.
export function strokeText(text, x, y, h) {
    const glyphs = [...text].map((c) => GLYPHS[c] ?? GLYPHS[' ']);
    const width = glyphs.reduce((s, [w]) => s + w + GAP, -GAP) * h;
    let cx = x - width / 2;
    const out = [];
    for (const [w, strokes] of glyphs) {
        for (const s of strokes) out.push(s.map(([u, v]) => [cx + u * h, y + v * h]));
        cx += (w + GAP) * h;
    }
    return out;
}
